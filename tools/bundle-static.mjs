// Bundles public/ (app code, styles, logo) into src/static.gen.js so the worker can serve them itself.
// Run before deploying: npm run build. A test checks the bundle matches public/.
import {readdirSync, readFileSync, writeFileSync, statSync} from 'node:fs';
import {join, relative, extname} from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const TYPES = {'.js': 'text/javascript;charset=utf-8', '.css': 'text/css;charset=utf-8', '.png': 'image/png', '.jpg': 'image/jpeg', '.svg': 'image/svg+xml', '.html': 'text/html;charset=utf-8', '.json': 'application/json'};

export function collect() {
  const out = {};
  const walk = (dir) => {
    for (const name of readdirSync(dir).sort()) {
      const p = join(dir, name);
      if (statSync(p).isDirectory()) walk(p);
      else if (TYPES[extname(name)]) out['/' + relative(join(ROOT, 'public'), p)] = {type: TYPES[extname(name)], b64: readFileSync(p).toString('base64')};
    }
  };
  walk(join(ROOT, 'public'));
  return out;
}
export const render = (files) => '// Generated by tools/bundle-static.mjs from public/. Do not edit; run npm run build.\nexport const STATIC = ' + JSON.stringify(files, null, 0) + ';\n';

if (import.meta.url === 'file://' + process.argv[1]) {
  writeFileSync(join(ROOT, 'src/static.gen.js'), render(collect()));
  console.log('Bundled', Object.keys(collect()).length, 'files into src/static.gen.js');
}
